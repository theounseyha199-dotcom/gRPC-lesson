package controller;

import com.example.common.grpc.payment.PaymentResponse;
import io.grpc.StatusRuntimeException;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.server.ResponseStatusException;
import service.PaymentClient;

// HTTP/JSON entry point; PaymentClient handles the separate gRPC request.
@RestController
@RequestMapping("/api/orders")
public class OrderController {

    private final PaymentClient paymentClient;

    public OrderController(PaymentClient paymentClient) {
        this.paymentClient = paymentClient;
    }

    @PostMapping
    public OrderResult create(@RequestBody CreateOrderRequest request) {
        // Reject invalid input before making a network call to Payment Service.
        if (request.orderId() == null
                || request.orderId().isBlank()
                || request.amountCents() <= 0) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST,
                    "Invalid orderId or amountCents"
            );
        }

        try {
            // PaymentResponse is generated by common-grpc from payment.proto.
            PaymentResponse payment = paymentClient.process(
                    request.orderId(), request.amountCents());

            // Translate the shared protobuf response into this API's JSON response.
            return new OrderResult(
                    request.orderId(),
                    payment.getPaymentId(),
                    payment.getSuccess() ? "PAID" : "PAYMENT_FAILED",
                    payment.getMessage()
            );
        } catch (StatusRuntimeException ex) {
            // Transport/RPC errors become HTTP 502; success=false is a normal payment result.
            throw new ResponseStatusException(
                    HttpStatus.BAD_GATEWAY,
                    "Payment gRPC call failed: " + ex.getStatus().getCode(),
                    ex
            );
        }
    }

    // HTTP DTOs are separate from the generated protobuf messages shared by the services.
    public record CreateOrderRequest(String orderId, long amountCents) {}

    public record OrderResult(
            String orderId, String paymentId, String status, String message
    ) {}
}
